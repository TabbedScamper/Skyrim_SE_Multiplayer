"""Builds Code/client/Games/Skyrim/Audio/LobbyPlaylist.inl: the lobby's shuffled soundtrack. Track files and folders
come from the installed masters' MUST records (ANAM); official soundtrack titles and lengths from UESP's Skyrim:Music
page (saved as uesp-skyrim-music.wiki, fetched 2026-10-01 with action=raw). Usage: make-playlist.py"""
import os, re, struct, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = r"C:\Program Files (x86)\Steam\steamapps\common\Skyrim Special Edition\Data"
MASTERS = ["Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm"]
MIN_SECONDS = 60  # stingers and short cues are left out


def game_paths():
    paths = {}
    def walk(data, off, end):
        while off < end:
            tag = data[off:off + 4]
            size = struct.unpack_from("<I", data, off + 4)[0]
            if tag == b"GRUP":
                walk(data, off + 24, off + size); off += size; continue
            if tag == b"MUST":
                flags = struct.unpack_from("<I", data, off + 8)[0]
                body = data[off + 24:off + 24 + size]
                if flags & 0x40000: body = zlib.decompress(body[4:])
                i = 0
                while i + 6 <= len(body):
                    st = body[i:i + 4]; sz = struct.unpack_from("<H", body, i + 4)[0]
                    if st == b"ANAM":
                        path = body[i + 6:i + 6 + sz].rstrip(b"\0").decode().replace("/", "\\").lstrip("\\")
                        path = re.sub(r"(?i)^data\\music\\", "", path)
                        stem = os.path.splitext(os.path.basename(path))[0].lower()
                        paths.setdefault(stem, os.path.splitext(path)[0] + ".xwm")
                    i += 6 + sz
            off += 24 + size
    for name in MASTERS:
        with open(os.path.join(DATA, name), "rb") as f:
            data = f.read()
        walk(data, 0, len(data))
    paths.setdefault("mus_maintheme", "Special\\MUS_MainTheme.xwm")  # played by the main menu, not a MUST record
    return paths


def uesp_rows():
    text = open(os.path.join(HERE, "uesp-skyrim-music.wiki"), encoding="utf-8").read()
    section = "Skyrim"
    rows = []
    for line in text.splitlines():
        heading = re.match(r"^===\s*(.+?)\s*===", line)
        if heading: section = heading.group(1)
        if not line.startswith("|") or line.startswith("|-") or line.startswith("|}"): continue
        cells = [c.strip() for c in line[1:].split("||")]
        time = next((c for c in cells if re.fullmatch(r"\d\d:\d\d", c)), None)
        files = next((c for c in cells if c.startswith("mus_")), None)
        if not time or not files: continue
        before = cells[:cells.index(files)]
        title = next((c for c in reversed(before) if c and not re.fullmatch(r"\d+", c)), "")
        minutes, seconds = map(int, time.split(":"))
        for stem in [f.strip() for f in files.split("/")]:
            rows.append((stem.lower(), title, minutes * 60 + seconds, section))
    return rows


def main():
    paths = game_paths()
    # Unnamed DLC tracks get the place they play in (from the file name).
    places = [("soulcairn", "Soul Cairn"), ("vampirecastle", "Castle Volkihar"), ("falmervalley", "Forgotten Vale"),
              ("apocrypha", "Apocrypha"), ("solstheim", "Solstheim")]
    out, seen, titles = [], set(), set()
    for stem, title, seconds, section in uesp_rows():
        if seconds < MIN_SECONDS or stem in seen or stem not in paths: continue
        seen.add(stem)
        if title:
            if title in titles: continue  # the same piece shipped under two file names
            titles.add(title)
        else:
            title = next((name for key, name in places if key in stem), section)
        out.append((title, paths[stem], seconds))
    lines = ["// Generated by Tools/Lobby/make-playlist.py from the installed masters (MUST ANAM) and UESP Skyrim:Music.",
             "// {title, path under Data\\Music, length in seconds}"]
    for title, path, seconds in out:
        lines.append('{{"{}", "{}", {}}},'.format(title.replace('"', '\\"'), path.replace("\\", "\\\\"), seconds))
    target = os.path.join(HERE, "..", "..", "Code", "client", "Games", "Skyrim", "Audio", "LobbyPlaylist.inl")
    open(target, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(out)} tracks -> {os.path.normpath(target)}")


if __name__ == "__main__":
    main()
